def get_refined_category(title, address, orig_cat):
    title_lower = title.lower()
    if any(k in title_lower for k in ["thermas", "aquátic", "toboagua", "splash", "piscina", "fantast", "unipark", "park", "diversõ"]):
        return "Parques de Diversão & Aquáticos"
    elif any(k in title_lower for k in ["zoo", "fazendinha", "bosque", "borboletário", "zoobotânico"]):
        return "Zoológicos, Bosques & Natureza"
    elif any(k in title_lower for k in ["cachoeira", "prainha", "mirante", "cristo", "corredeira", "lagoa", "morro", "orla", "balneário"]):
        return "Cachoeiras, Prainhas & Mirantes"
    elif any(k in title_lower for k in ["museu", "marp", "pateo", "marco zero", "sampa sky", "estação", "funicular", "trenzinho", "maria fumaça", "caixa cultural", "torre", "observatório", "paleontologia", "sambódromo", "cera"]):
        return "Atrações Turísticas, Museus & Cultura"
    elif any(k in title_lower for k in ["parque", "praça", "quintal", "jardim"]):
        return "Áreas de Lazer, Praças & Parques"
    else:
        return "Atrações Turísticas & Lazer"

